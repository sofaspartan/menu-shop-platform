function retailHours(): BusinessHoursDay[] {
  return [0, 1, 2, 3, 4, 5, 6].map((day) => ({
    day: day as BusinessHoursDay['day'],
    closed: day === 0,
    open: '10:00',
    close: day === 5 || day === 6 ? '19:00' : '18:00',
  }))
}

